const {spawn}=require('node:child_process');
const assert=require('node:assert/strict');
const path=require('node:path'),fs=require('node:fs');
const pw=require(process.env.PLAYWRIGHT_MODULE||(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright':'playwright'));
(async()=>{
 const root=path.resolve(__dirname,'..'),out=path.join(__dirname,'artifacts');fs.mkdirSync(out,{recursive:true});
 const server=spawn(process.env.AURORA_TEST_PYTHON||'python',['-m','uvicorn','tests.browser_release_server:app','--host','127.0.0.1','--port','8113'],{cwd:root,stdio:['ignore','ignore','pipe']});let browser;
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('startup timeout')),15000);server.stderr.on('data',d=>{if(d.toString().includes('Application startup complete')){clearTimeout(timer);resolve()}})});
  browser=await pw.chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-gpu','--no-zygote']});
  const page=await browser.newPage({viewport:{width:1366,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8113');
  await page.getByRole('img',{name:'Velas com escala de preços e horários de Brasília'}).waitFor();
  const svg=page.locator('svg');assert(await svg.locator('text').count()>=8);
  await page.getByRole('button',{name:'Ampliar gráfico'}).click();
  await page.getByRole('button',{name:'Ver velas anteriores'}).click();
  await page.getByRole('button',{name:'Atual',exact:true}).click();
  await page.getByText('Configurações',{exact:true}).click();
  await page.getByLabel('Sinais por hora',{exact:true}).fill('7');
  await page.getByRole('button',{name:'Salvar limites',exact:true}).click();
  await page.waitForFunction(async()=>((await(await fetch('/api/state')).json()).settings.hourly_limit===7));
  await page.reload();
  await page.getByText('Configurações',{exact:true}).click();
  assert.equal(await page.getByLabel('Sinais por hora',{exact:true}).inputValue(),'7');
  await page.getByRole('link',{name:'Painel',exact:true}).click();
  await page.getByRole('button',{name:'Iniciar',exact:true}).click();
  await page.waitForFunction(async()=>((await(await fetch('/api/state')).json()).signals.length===2));
  await page.getByRole('button',{name:'Parar',exact:true}).click();
  await page.request.post('http://127.0.0.1:8113/_test/expire');
  await page.getByRole('link',{name:'Aprendizado',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Resultados dos sinais"]')?.textContent.includes('Vitórias: 2'));
  assert((await page.getByLabel('Resultados dos sinais').innerText()).includes('100.00%'));
  await page.screenshot({path:path.join(out,'results-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(out,'results-mobile.png'),fullPage:true});
  await page.goto('http://127.0.0.1:8113/conexoes');
  assert.equal(await page.getByLabel('Chave Gemini',{exact:true}).count(),0);
  await page.getByText('Explicações dos sinais: motor técnico local. Sem chave ou consumo de IA.',{exact:true}).waitFor();
  assert((await(await page.request.get('http://127.0.0.1:8113/api/credentials')).json()).explanation_source==='motor');
  await page.request.post('http://127.0.0.1:8113/_test/public_sources');
  await page.reload();
  assert((await page.request.put('http://127.0.0.1:8113/api/connection',{data:{provider:'binance'}})).ok());
  await page.waitForFunction(async()=>((await(await fetch('/api/state')).json()).provider==='binance'));
  await page.goto('http://127.0.0.1:8113');
  await page.getByRole('img',{name:'Velas com escala de preços e horários de Brasília'}).waitFor();
  await page.waitForFunction(()=>document.body.textContent.includes('BTC/USDT'));
  assert(!await page.getByRole('button',{name:'EUR/USD',exact:true}).count());
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.goto('http://127.0.0.1:8113/conexoes');
  assert((await page.request.put('http://127.0.0.1:8113/api/connection',{data:{provider:'coinbase'}})).ok());
  await page.waitForFunction(async()=>((await(await fetch('/api/state')).json()).provider==='coinbase'));
  await page.goto('http://127.0.0.1:8113');
  await page.waitForFunction(()=>document.body.textContent.includes('BTC/USD'));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);console.log('PASS chart, limits, signals, totals, responsive layout, engine explanations, Binance/Coinbase selection and assets');
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1});
